"""Export pipelines: .tex bundle (zip), .docx, references.bib."""
from __future__ import annotations

import io
import re
import zipfile
from typing import Any

from . import latex


def tex_bundle(
    *,
    tex: str,
    assets: list[dict[str, Any]],
    title: str,
) -> bytes:
    """A self-contained folder for Overleaf: main.tex + figures/ + references.bib."""
    from . import compiler
    from .latex import _asset_key

    buf = io.BytesIO()
    fig_files = compiler.figure_files(assets)
    raw_svg = {
        f"figures/{a['name']}": a["data"]
        for a in assets
        if a.get("data") and str(a.get("name", "")).lower().endswith(".svg")
    }
    with zipfile.ZipFile(buf, "w", zipfile.ZIP_DEFLATED) as zf:
        zf.writestr("main.tex", tex)
        zf.writestr(
            "README.txt",
            (
                f"{title}\n"
                "Generated by AI2LaTeX.\n\n"
                "Compile with:  pdflatex main.tex   (run twice for references)\n"
                "or upload this folder to Overleaf — figures are already included.\n"
            ),
        )
        for rel, blob in fig_files.items():
            zf.writestr(rel, blob)
        for rel, blob in raw_svg.items():
            zf.writestr(rel, blob)
        zf.writestr(
            "references.bib",
            "@misc{rfc793,\n"
            '  author = {J. Postel},\n'
            '  title = {Transmission Control Protocol},\n'
            "  year = {1981},\n"
            "  note = {RFC 793}\n"
            "}\n",
        )
    return buf.getvalue()


def docx_bytes(
    *,
    title: str,
    author: str,
    affiliation: str,
    date: str,
    abstract: str,
    blocks: list[dict[str, Any]],
    settings: dict[str, Any],
    assets: dict[str, dict[str, Any]],
) -> bytes:
    from docx import Document
    from docx.enum.text import WD_ALIGN_PARAGRAPH
    from docx.shared import Pt, RGBColor

    doc = Document()
    normal = doc.styles["Normal"]
    normal.font.name = "Times New Roman"
    normal.font.size = Pt(float(settings.get("fontSize", 11)))

    accent_hex = latex.ACCENTS.get(str(settings.get("accent", "navy")), "002855")
    accent_rgb = RGBColor.from_string(accent_hex.upper())

    heading = doc.add_heading(title, level=0)
    for run in heading.runs:
        run.font.color.rgb = accent_rgb

    p = doc.add_paragraph(author)
    p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    p2 = doc.add_paragraph(affiliation + ("\n" + date if date else ""))
    p2.alignment = WD_ALIGN_PARAGRAPH.CENTER
    for run in p2.runs:
        run.font.size = Pt(10)
        run.font.color.rgb = RGBColor(0x64, 0x74, 0x8B)

    if abstract:
        doc.add_heading("Abstract", level=1)
        doc.add_paragraph(latex.latex_to_plain(abstract))

    table_no = 0
    fig_no = 0
    for block in blocks:
        kind = block.get("type")
        if kind == "section":
            level = min(4, max(1, int(block.get("level", 1))))
            doc.add_heading(str(block.get("title", "")), level=level)
        elif kind == "paragraph":
            para = doc.add_paragraph(latex.latex_to_plain(str(block.get("text", ""))))
            para.alignment = (
                WD_ALIGN_PARAGRAPH.JUSTIFY
                if settings.get("justified", True)
                else WD_ALIGN_PARAGRAPH.LEFT
            )
        elif kind == "bullets":
            for item in block.get("items", []):
                doc.add_paragraph(latex.latex_to_plain(str(item)), style="List Bullet")
        elif kind == "equation":
            eq = doc.add_paragraph()
            eq.alignment = WD_ALIGN_PARAGRAPH.CENTER
            run = eq.add_run(latex.latex_to_plain(str(block.get("latex", ""))))
            run.italic = True
        elif kind == "table":
            cols = block.get("columns", [])
            rows = block.get("rows", [])
            if cols and rows:
                table_no += 1
                cap = doc.add_paragraph()
                crun = cap.add_run(
                    f"TABLE {table_no}. " + str(block.get("caption", "")).upper()
                )
                crun.bold = True
                crun.font.size = Pt(9)
                crun.font.color.rgb = accent_rgb
                table = doc.add_table(rows=1 + len(rows), cols=len(cols))
                table.style = "Table Grid"
                for ci, c in enumerate(cols):
                    cell = table.rows[0].cells[ci]
                    cell.text = latex.latex_to_plain(str(c))
                    for para in cell.paragraphs:
                        for r in para.runs:
                            r.bold = True
                for ri, row in enumerate(rows, start=1):
                    for ci in range(len(cols)):
                        val = str(row[ci]) if ci < len(row) else ""
                        table.rows[ri].cells[ci].text = latex.latex_to_plain(val)
        elif kind == "figure":
            fig_no += 1
            asset = assets.get(str(block.get("assetId")))
            if asset and asset.get("data"):
                try:
                    doc.add_picture(io.BytesIO(asset["data"]))
                except Exception:
                    pass
            cap = doc.add_paragraph()
            crun = cap.add_run(f"Figure {fig_no}. {block.get('caption', '')}")
            crun.italic = True
            crun.font.size = Pt(9)
        elif kind == "pagebreak":
            doc.add_page_break()

    out = io.BytesIO()
    doc.save(out)
    return out.getvalue()


def safe_name(title: str) -> str:
    cleaned = re.sub(r"[^\w\s-]", "", title).strip().replace(" ", "-")
    return cleaned[:60] or "document"
